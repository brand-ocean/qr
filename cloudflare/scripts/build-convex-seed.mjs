#!/usr/bin/env node
// Generates cloudflare/convex/seedData.ts from the app's videos.ts dataset,
// so `npx convex run seed:run` can bootstrap Convex with the current cards.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const videosPath = path.resolve(here, '../../src/data/videos.ts');
const outPath = path.resolve(here, '../convex/seedData.ts');

const { VIDEOS } = await import(videosPath);

const cards = VIDEOS.map((v) => ({
  cardId: v.id,
  quote: v.quote,
  videoId: v.videoId,
  startTime: v.startTime,
  endTime: v.endTime,
  year: v.year,
  contentWarning: v.contentWarning,
}));

const header = `// AUTO-GENERATED by cloudflare/scripts/build-convex-seed.mjs — do not edit.
// Source: src/data/videos.ts. Regenerate with: node scripts/build-convex-seed.mjs

export type SeedCard = {
  readonly cardId: string;
  readonly quote: string;
  readonly videoId: string;
  readonly startTime: number;
  readonly endTime: number;
  readonly year: number;
  readonly contentWarning: boolean;
};

export const SEED_CARDS: ReadonlyArray<SeedCard> = ${JSON.stringify(cards, null, 2)};
`;

fs.writeFileSync(outPath, header);
console.log(
  `Wrote ${cards.length} cards to ${path.relative(process.cwd(), outPath)}`,
);
